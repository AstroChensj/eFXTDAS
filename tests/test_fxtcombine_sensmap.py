def test_build_fxtsensmap_command() -> None:
    """The Stage-6 command should target the stacked products.

    Returns
    -------
    None
    """
    cmd = pipeline._build_fxtsensmap_command(
        "/tmp/stack bkg.fits",
        "/tmp/stack expmap.fits",
        "/tmp/stack psfprod.fits",
        "/tmp/stack sensmap.fits",
        0.9,
        DEFAULT_ECF,
        6.0,
        jobs=4,
        mask="/tmp/stack mask.fits",
    )

    assert cmd == (
        'fxtsensmap --bkgmap "/tmp/stack bkg.fits" '
        '--expmap "/tmp/stack expmap.fits" '
        '--psfprod "/tmp/stack psfprod.fits" '
        "--eef 0.9 "
        f"--ecf {float(DEFAULT_ECF)} "
        "--likemin 6.0 "
        "--jobs 4 "
        '--mask "/tmp/stack mask.fits" '
        '--out "/tmp/stack sensmap.fits"'
    )


def test_build_quickview_command() -> None:
    """The Stage-7 command should target quickview output and log paths.

    Returns
    -------
    None
    """
    cmd = pipeline._build_quickview_command(
        "/tmp/stack dir",
        "/tmp/stack dir/quickview.png",
        dpi=180,
        log_file="/tmp/stack dir/quickview.log",
    )

    assert cmd == (
        'fxtcombine-quickview "/tmp/stack dir" '
        '--out "/tmp/stack dir/quickview.png" '
        "--dpi 180 "
        '--log-file "/tmp/stack dir/quickview.log"'
    )
    assert "--r90-stride" not in cmd


def test_run_quickview_stage_warns_without_raising(monkeypatch, tmp_path) -> None:
    """Quickview failures should be reported without failing completed products.

    Parameters
    ----------
    monkeypatch : pytest.MonkeyPatch
        Fixture used to replace command execution.
    tmp_path : pathlib.Path
        Temporary directory.

    Returns
    -------
    None
    """

    def _raise_run_cmd(cmd: str, logger=None, logname=None, cwd=None):
        raise RuntimeError("plot failed")

    monkeypatch.setattr(pipeline, "run_cmd", _raise_run_cmd)

    ok = pipeline._run_quickview_stage(str(tmp_path), str(tmp_path / "quickview.png"), dpi=100, logger=None)

    assert ok is False


